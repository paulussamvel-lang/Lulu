def workflow_markdown(records):
    lines = []
    for stage in (*STAGES, COMMERCIAL):
        steps = [step for step in stage.steps if records.get(step.key)]
        if not steps:
            continue
        lines.extend(('', f'## {stage.title}'))
        for step in steps:
            record = records[step.key]
            lines.extend(('', f'### {step.title}', '已完成' if record.get('done') else '进行中'))
            for label, key in (('输入与依据', 'input'), ('产物与记录', 'output')):
                if record.get(key):
                    lines.extend(('', f'**{label}**', record[key]))
    return lines
